"""Build Flutter paths from the approved Xagent v1 outlined SVG masters."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

APP = Path(__file__).resolve().parents[1]
MASTER = APP.parent / 'design/Xagent-Identity-v1/01_Vector'
OUTPUT = APP / 'lib/ui/shell/brand_glyph.g.dart'
COMMANDS = {'M': ('moveTo', 2), 'L': ('lineTo', 2), 'Q': ('quadraticBezierTo', 4), 'Z': ('close', 0)}


def contours(source):
    runs = re.findall(r'([A-Za-z])([^A-Za-z]*)', source)
    for op, values in runs:
        method, count = COMMANDS[op]
        args = values.strip().split()
        if len(args) != count:
            raise ValueError(f'Unsupported path segment {op} {values}')
        yield f'    ..{method}({", ".join(args)})'


def paths(name):
    return ET.parse(MASTER / name).findall('.//{http://www.w3.org/2000/svg}path')


def dart_path(name, shapes, even_odd=False):
    statements = ['    ..fillType = PathFillType.evenOdd'] if even_odd else []
    for shape in shapes:
        statements.extend(contours(shape.attrib['d']))
    return f'  static final {name} = Path()\n' + '\n'.join(statements) + ';\n'


faces = paths('mark/color.svg')
moment_x = moment_y = area = 0
for face in faces:
    coords = list(map(float, re.findall(r'-?\d+(?:\.\d+)?', face.attrib['d'])))
    corners = list(zip(coords[::2], coords[1::2]))
    edges = list(zip(corners, corners[1:] + corners[:1]))
    weights = [x*v-u*y for (x,y),(u,v) in edges]
    sign = 1 if sum(weights) > 0 else -1
    area += sign * sum(weights)
    for ((x,y),(u,v)), weight in zip(edges, weights):
        moment_x += sign * weight * (x+u)
        moment_y += sign * weight * (y+v)
text = """// Generated by tool/make_brand_mark.py from the Xagent v1 SVG masters.
// dart format off
import 'dart:ui';

abstract final class BrandGlyph {
  static const aspect = 357 / 280;
  static const box = Rect.fromLTWH(0, 0, 357, 280);
  static const ink = Color(0xFF002226);
"""
text += f'  static const centroid = Offset({moment_x/(3*area):.6f}, {moment_y/(3*area):.6f});\n'
colors = list(dict.fromkeys(face.attrib['fill'] for face in faces))
for index, color in enumerate(colors):
    text += dart_path(f'face{index}', [p for p in faces if p.attrib['fill'] == color])
text += dart_path('word', paths('wordmark/ink.svg'), True)
text += '  static void paint(Canvas canvas, [Color? tint]) {\n    final paint = Paint();\n'
for i, c in enumerate(colors):
    text += f'    canvas.drawPath(face{i}, paint..color = tint ?? const Color(0xFF{c[1:]}));\n'
text += '  }\n}\n'
OUTPUT.write_text(text)
